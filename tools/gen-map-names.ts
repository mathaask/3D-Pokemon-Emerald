// Generates src/game/mapNames.ts (MAP_NAMES[group][num] -> decomp map identifier) from
// vendor/pokeemerald-src/data/maps/map_groups.json. Usage: npx tsx tools/gen-map-names.ts
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const jsonPath = path.join(root, 'vendor/pokeemerald-src/data/maps/map_groups.json');
const groups = JSON.parse(fs.readFileSync(jsonPath, 'utf8')) as Record<string, string[]> & {
  group_order: string[];
};

const lines: string[] = [];
lines.push('// AUTO-GENERATED by tools/gen-map-names.ts from pokeemerald data/maps/map_groups.json.');
lines.push('// MAP_NAMES[group][num] is the decomp identifier of each map (e.g. "LittlerootTown").');
lines.push('// GROUP_NAMES[group] is the decomp name of each map group array.');
lines.push('export const GROUP_NAMES: string[] = [');
for (const g of groups.group_order) lines.push(`  '${g.replace(/^gMapGroup_/, '')}',`);
lines.push('];');
lines.push('');
lines.push('export const MAP_NAMES: string[][] = [');
let total = 0;
groups.group_order.forEach((g, i) => {
  const maps = groups[g];
  total += maps.length;
  lines.push(`  // ${i}: ${g}`);
  lines.push('  [');
  for (let j = 0; j < maps.length; j += 4) {
    lines.push('    ' + maps.slice(j, j + 4).map((m) => `'${m}'`).join(', ') + ',');
  }
  lines.push('  ],');
});
lines.push('];');
lines.push('');
lines.push('/** Finds [group, num] of a map by decomp name, or undefined. */');
lines.push('export function findMap(name: string): [number, number] | undefined {');
lines.push('  for (let g = 0; g < MAP_NAMES.length; g++) {');
lines.push('    const n = MAP_NAMES[g].indexOf(name);');
lines.push('    if (n >= 0) return [g, n];');
lines.push('  }');
lines.push('  return undefined;');
lines.push('}');
lines.push('');

const out = path.join(root, 'src/game/mapNames.ts');
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${path.relative(root, out)}: ${groups.group_order.length} groups, ${total} maps`);
