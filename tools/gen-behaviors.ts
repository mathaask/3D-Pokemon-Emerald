// Generates src/game/behaviors.ts (metatile behavior ids) from the pokeemerald header.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const src = fs.readFileSync(path.join(root, 'vendor/pokeemerald-src/include/constants/metatile_behaviors.h'), 'utf8');
const body = src.slice(src.indexOf('{') + 1, src.indexOf('}'));
const names: string[] = [];
for (const raw of body.split('\n')) {
  const line = raw.replace(/\/\/.*$/, '').trim();
  const m = /^(MB_\w+)\s*(=\s*[^,]+)?,?$/.exec(line);
  if (m) names.push(m[1]);
}
const out = `// AUTO-GENERATED by tools/gen-behaviors.ts — metatile behavior ids (pokeemerald).
export const MB = {
${names.map((n, i) => `  ${n.slice(3)}: 0x${i.toString(16)},`).join('\n')}
} as const;
`;
fs.writeFileSync(path.join(root, 'src/game/behaviors.ts'), out);
console.log(`${names.length} behaviors`);
